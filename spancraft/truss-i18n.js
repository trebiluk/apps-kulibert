const PACKS = { en: EN, simple: SIMPLE, es: ES, uk: UK, ru: RU, ar: AR, "fa-AF": FA, rw: RW, ti: TI };

export const NEEDS_NATIVE_CHECK = ["fa-AF", "rw", "ti"];

function classicTheme() {
  if (document.documentElement.dataset.theme === "classic") return true;
  try {
    if (location.pathname.indexOf("/holdit/classic") === 0) return true;
  } catch (e) {}
  return false;
}

let heard = "";
if (typeof window !== "undefined") {
  window.addEventListener("kulibert-lang", (ev) => {
    const lang = ev && ev.detail && ev.detail.lang;
    if (OK[lang]) heard = lang;
  });
}

export function uiLang() {
  if (classicTheme()) return "en";
  if (OK[heard]) return heard;
  let q = "";
  try { q = new URLSearchParams(location.search).get("lang") || ""; } catch (e) {}
  if (!q) {
    try {
      if (window.parent && window.parent !== window) {
        q = new URLSearchParams(window.parent.location.search).get("lang") || "";
      }
    } catch (e2) {}
  }
  if (OK[q]) return q;
  try {
    const prefs = window.KulibertPrefs;
    if (prefs && typeof prefs.lang === "string" && OK[prefs.lang]) return prefs.lang;
  } catch (e3) {}
  return "en";
}

export function t(key) {
  const lang = uiLang();
  const pack = PACKS[lang] || EN;
  if (pack[key]) return pack[key];
  const extra = EXTRA[lang] || EXTRA.en;
  if (extra && extra[key]) return extra[key];
  if (EN[key]) return EN[key];
  if (EXTRA.en && EXTRA.en[key]) return EXTRA.en[key];
  return "";
}

const SHARED = {
  retry: "retry", help: "help", levels: "levels", settings: "settings",
  close: "close", menu: "menu", read: "readAloud", room: "home", back: "back",
  language: "language",
};

export function chrome(name) {
  const key = SHARED[name];
  if (key && window.KulibertI18n && typeof window.KulibertI18n.t === "function") {
    const hit = window.KulibertI18n.t(key);
    if (hit) return hit;
  }
  return t(name) || EN[name] || "";
}

export function applyDir() {
  const html = document.documentElement;
  if (classicTheme()) {
    if (html.getAttribute("dir") === "rtl") html.setAttribute("dir", "ltr");
    return;
  }
  const lang = uiLang();
  const dir = lang === "ar" || lang === "fa-AF" ? "rtl" : "ltr";
  html.setAttribute("dir", dir);
  html.lang = lang === "simple" ? "en" : lang;
}

export function noVoiceLine() {
  if (window.KulibertI18n && typeof window.KulibertI18n.t === "function") {
    const hit = window.KulibertI18n.t("noVoice");
    if (hit) return hit;
  }
  return "No voice yet. Read the words.";
}
