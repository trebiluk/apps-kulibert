export function gingerLang() {
  try {
    const q = new URLSearchParams(location.search);
    if (q.get("theme") === "classic" || q.get("hub") === "classic") return "en";
    if (typeof localStorage !== "undefined" && localStorage.getItem("tech-room-hub") === "classic") return "en";
  } catch { /* ignore */ }
  const prefs = window.KulibertPrefs;
  const raw = prefs && (typeof prefs.lang === "string" ? prefs.lang : prefs.get && prefs.get().lang);
  let bag = false;
  try {
    bag = !!(localStorage.getItem("kulibert-prefs-v1") || /(?:^#|&)kp=/.test(location.hash || ""));
  } catch { /* ignore */ }
  if (bag && raw) {
    if (raw === "fa") return "fa-AF";
    if (G[raw]) return raw;
  }
  try {
    const fromQ = new URLSearchParams(location.search).get("lang");
    if (fromQ === "fa" || fromQ === "fa-AF") return "fa-AF";
    if (fromQ && G[fromQ]) return fromQ;
  } catch { /* ignore */ }
  if (raw === "fa") return "fa-AF";
  if (raw && G[raw]) return raw;
  return "en";
}

export function gingerDir(lang) {
  const use = lang || gingerLang();
  return use === "ar" || use === "fa-AF" ? "rtl" : "ltr";
}

const SHARED = { help: "help" };

export function tr(key, lang) {
  const use = lang || gingerLang();
  const pack = G[use] || G.en;
  const own = pack[key] || (use === "simple" ? G.en[key] : "") || G.en[key];
  if (SHARED[key] && window.KulibertI18n && typeof window.KulibertI18n.t === "function") {
    const shared = window.KulibertI18n.t(SHARED[key]);
    if (shared && shared !== SHARED[key]) return shared;
  }
  return own || G.en[key] || "";
}

export function roomLabel(name, lang) {
  const key = "room." + String(name || "");
  const use = lang || gingerLang();
  const pack = G[use] || G.en;
  if (pack[key] || G.en[key]) return tr(key, use);
  return String(name || "");
}

