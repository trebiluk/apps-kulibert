def ov_dots(a, col, seed, n=7, r0=2):            # iron: round rusty dots
    im = img(a); d = ImageDraw.Draw(im); g = rng(seed)
    for _ in range(n):
        x, y = g.integers(3, S-4, 2); rr = r0 + int(g.integers(0, 2))
        d.ellipse([x-rr, y-rr, x+rr, y+rr], fill=tuple(hexc(col).astype(int)), outline=(70, 40, 30))
    return arr(im)
def ov_streaks(a, c1, c2, seed, n=4):             # copper: diagonal orange streaks with green tips
    im = img(a); d = ImageDraw.Draw(im); g = rng(seed)
    for _ in range(n):
        x, y = g.integers(0, S-10, 2); L = int(g.integers(6, 11))
        d.line([x, y, x+L, y+L//2], fill=tuple(hexc(c1).astype(int)), width=2)
        d.rectangle([x+L-1, y+L//2-1, x+L, y+L//2], fill=tuple(hexc(c2).astype(int)))
    return arr(im)
def ov_flakes(a, col, seed, n=10):                # zinc: thin grey-blue flakes (3x1 / 1x3)
    g = rng(seed); c = hexc(col)
    for i in range(n):
        x, y = g.integers(1, S-4, 2)
        if i % 2: a[y, x:x+4, :3] = c; a[y+1, x+1:x+3, :3] = c * 0.8
        else: a[y:y+4, x, :3] = c; a[y+1:y+3, x+1, :3] = c * 0.8
    return a
def ov_squares(a, col, seed, n=6):                # tin: dark brown squares with a light corner
    g = rng(seed); c = hexc(col)
    for _ in range(n):
        x, y = g.integers(1, S-5, 2); a[y:y+4, x:x+4, :3] = c; a[y, x, :3] = c + 60
    return a
def ov_spikes(a, col, seed, n=5):                 # quartz: white crystal spikes
    im = img(a); d = ImageDraw.Draw(im); g = rng(seed); c = tuple(hexc(col).astype(int))
    for _ in range(n):
        x, y = g.integers(4, S-4), g.integers(10, S-2); h = int(g.integers(5, 9))
        d.polygon([(x-2, y), (x, y-h), (x+2, y)], fill=c, outline=(150, 160, 170))
    return arr(im)
def ov_lines(a, col, seed, n=5):                  # silver: thin bright lines
    im = img(a); d = ImageDraw.Draw(im); g = rng(seed); c = tuple(hexc(col).astype(int))
    for _ in range(n):
        x, y = g.integers(0, S-8, 2); d.line([x, y, x+int(g.integers(5, 9)), y-int(g.integers(-2, 3))], fill=c, width=1)
    return arr(im)
def ov_vein(a, col, seed):                         # gold: one yellow wiggly vein in quartz-white rim
    im = img(a); d = ImageDraw.Draw(im); g = rng(seed)
    pts = [(0, 10 + int(g.integers(0, 12)))]
    for x in range(4, S + 4, 4): pts.append((x, int(np.clip(pts[-1][1] + g.integers(-4, 5), 3, S-4))))
    d.line(pts, fill=(226, 222, 210), width=4); d.line(pts, fill=tuple(hexc(col).astype(int)), width=2)
    return arr(im)
def ov_glow(a, col, seed, n=9):                    # glow moss: teal dots with a 1 px halo
    g = rng(seed); c = hexc(col)
    for _ in range(n):
        x, y = g.integers(2, S-3, 2)
        a[y-1:y+2, x-1:x+2, :3] = a[y-1:y+2, x-1:x+2, :3] * 0.5 + c * 0.5; a[y, x, :3] = c + 30
    return a
def ov_grains(a, col, seed, n=40):                 # black sand / ilmenite style grains
    return speckle(a, col, n / (S*S), seed)
def ov_flecks(a, col, seed, n=8):                  # platinum: silver-white rounded flecks, dark rim
    im = img(a); d = ImageDraw.Draw(im); g = rng(seed); c = tuple(hexc(col).astype(int))
    for _ in range(n):
        x, y = g.integers(3, S-4, 2); d.rectangle([x-1, y-1, x+1, y+1], fill=c, outline=(40, 40, 50))
