def minimap(key, col, pat):
    a = np.zeros((16, 16, 4)); a[..., :3] = hexc(col); a[..., 3] = 255; dk = hexc(col) * 0.55
    yy, xx = np.mgrid[0:16, 0:16]
    m = {'dots': (xx % 4 == 1) & (yy % 4 == 1), 'crosshatch': ((xx + yy) % 6 == 0) | ((xx - yy) % 6 == 0), 'stripes': (yy % 4 == 0),
         'waves': ((yy + np.round(1.5 * np.sin(xx / 2.5))).astype(int) % 5 == 0), 'zigzag': ((yy + np.abs((xx % 8) - 4)) % 6 == 0),
         'checker': ((xx // 4 + yy // 4) % 2 == 0) & ((xx + yy) % 2 == 0), 'waves2': ((yy + np.round(1.5 * np.sin(xx / 2.5))).astype(int) % 3 == 0),
         'bricks': (yy % 4 == 0) | ((xx + (yy // 4 % 2) * 4) % 8 == 0)}[pat]
    a[m, :3] = dk; return img(a)

