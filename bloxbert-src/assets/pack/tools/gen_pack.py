def door_half(top, style):
    base = {'wood': '#a8743f', 'glass': '#9a6b3a', 'metal': '#7d8590', 'slide': '#b8c2cc', 'workshop': '#4f6fa8'}[style]
    a = np.zeros((S, S, 4)); x0, x1 = 6, 26
