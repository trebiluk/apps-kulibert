def bush(leaf, fruit, shape='dots'):
    def f(d, g):
        for i in range(7):
            x = 4 + i * 4; d.line([x, S-1, x + int(g.integers(-3, 4)), 10 + int(g.integers(0, 8))], fill=tuple(hexc(leaf).astype(int)), width=2)
        for _ in range(7 if shape == 'dots' else 4):
            x, y = int(g.integers(4, S-5)), int(g.integers(6, 20))
            if shape == 'dots': d.ellipse([x-2, y-2, x+2, y+2], fill=tuple(hexc(fruit).astype(int)))
            elif shape == 'cob': d.rectangle([x-1, y-3, x+2, y+4], fill=tuple(hexc(fruit).astype(int)), outline=(120, 100, 30))
            elif shape == 'flower':
                c = tuple(hexc(fruit).astype(int))
                for dx, dy in [(-2, 0), (2, 0), (0, -2), (0, 2)]: d.ellipse([x+dx-1, y+dy-1, x+dx+1, y+dy+1], fill=c)
                d.point((x, y), fill=(240, 200, 60))
    return f

