GLARE = np.array([238, 243, 247])  # snow #EEF3F7 is the brightest allowed surface colour (WORLD-2 §4)

def rng(name):
    return np.random.default_rng(int(hashlib.sha1(name.encode()).hexdigest()[:8], 16))
def hexc(h):
    h = h.lstrip('#'); return np.array([int(h[i:i+2], 16) for i in (0, 2, 4)], dtype=float)
def kenney(name, folder='Tiles'):
    im = Image.open(f'{KV}/PNG/{folder}/{name}.png').convert('RGBA')
    return im.resize((S, S), Image.BOX)
def arr(im): return np.asarray(im.convert('RGBA')).astype(float)
def img(a): return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')
def deglare(a):
    """Clamp every opaque pixel so no channel set reaches pure white; brightest = #EEF3F7."""
    rgb = a[..., :3]; lum = rgb.mean(-1, keepdims=True)
    hot = (rgb > GLARE).any(-1, keepdims=True)
    a[..., :3] = np.where(hot, np.minimum(rgb, GLARE), rgb)
    return a
def noise_tile(base, var=14, seed='x', cluster=2, lo=None):
    r = rng(seed); n = S // cluster
    v = r.normal(0, var, (n, n, 1)).repeat(cluster, 0).repeat(cluster, 1)
    a = np.zeros((S, S, 4)); a[..., :3] = hexc(base) + v; a[..., 3] = 255
    return a
def speckle(a, color, frac, seed, size=1):
    r = rng(seed); c = hexc(color)
    for _ in range(int(frac * S * S / (size * size))):
        x, y = r.integers(0, S - size + 1, 2); a[y:y+size, x:x+size, :3] = c + r.normal(0, 6, 3)
    return a
def bevel(a, d=18):
    a[0, :, :3] += d; a[:, 0, :3] += d; a[-1, :, :3] -= d; a[:, -1, :3] -= d; return a

