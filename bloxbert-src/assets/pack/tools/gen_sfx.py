def write_wav(x, path):
    x = x / (np.abs(x).max() + 1e-9) * 0.5; x = (x * 32767).astype(np.int16)
    with wave.open(path, 'wb') as w: w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(x.tobytes())
