def find(pack, stem):
    m = [p for p in glob.glob(f'{K}/{pack}/**/*.ogg', recursive=True) if os.path.basename(p)[:-4] == stem]
    if not m: raise SystemExit(f'missing {pack}/{stem}')
    return m[0]
def enc(src, out, af='loudnorm=I=-18:TP=-6:LRA=7'):
    for ext, codec in (('ogg', ['-c:a', 'libvorbis', '-q:a', '3']), ('mp3', ['-c:a', 'libmp3lame', '-b:a', '96k'])):
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-ac', '1', '-ar', str(SR), '-af', af, '-map_metadata', '-1', '-fflags', '+bitexact', *codec, f'{out}.{ext}'], check=True)
def env(n, a=0.005, r=0.1):
    t = np.arange(n) / SR; e = np.minimum(1, t / a) * np.exp(-t / r); return e
def tone(f, d, wave_='sine', a=0.005, r=0.15, vib=0):
    n = int(SR * d); t = np.arange(n) / SR; ph = 2 * np.pi * np.cumsum(np.full(n, f) * (1 + vib * np.sin(2 * np.pi * 5 * t))) / SR
    s = {'sine': np.sin(ph), 'tri': 2 / np.pi * np.arcsin(np.sin(ph)), 'soft': np.sin(ph) + 0.3 * np.sin(2 * ph) + 0.1 * np.sin(3 * ph)}[wave_]
    return s * env(n, a, r)
def sweep(f0, f1, d, r=0.2, wave_='sine'):
    n = int(SR * d); f = np.geomspace(f0, f1, n); ph = 2 * np.pi * np.cumsum(f) / SR
    s = np.sin(ph) if wave_ == 'sine' else 2 / np.pi * np.arcsin(np.sin(ph)); return s * env(n, 0.005, r)
def noise(d, lp=4000, r=0.1, seed=1):
    n = int(SR * d); x = np.random.default_rng(seed).normal(0, 1, n); a = np.exp(-2 * np.pi * lp / SR); y = np.zeros(n)
    for i in range(1, n): y[i] = (1 - a) * x[i] + a * y[i - 1]
    return y / (np.abs(y).max() + 1e-9) * env(n, 0.003, r)
def cat(*xs, gap=0.0):
    out = []
    for x in xs: out += [x, np.zeros(int(SR * gap))]
    return np.concatenate(out)
def mix(*xs):
    n = max(len(x) for x in xs); o = np.zeros(n)
    for x in xs: o[:len(x)] += x
    return o
